// One-off generator: produces the SVG path data + validator marker
// coordinates for WorldMap.tsx from real geographic data (world-atlas +
// d3-geo Natural Earth projection).
//
// These libraries are NOT app dependencies (no d3/topojson code ships to
// the browser) — they're only needed to regenerate worldMapData.ts. Install
// them temporarily, run the script, then uninstall:
//   npm i -D d3-geo topojson-client world-atlas
//   node scripts/generate-world-map.cjs
//   npm uninstall d3-geo topojson-client world-atlas
const fs = require("fs");
const path = require("path");
const d3geo = require("d3-geo");
const topojson = require("topojson-client");
const world = require("world-atlas/countries-110m.json");

const WIDTH = 1000;
const HEIGHT = 500;

const land = topojson.merge(world, world.objects.countries.geometries);
const projection = d3geo.geoNaturalEarth1().fitSize([WIDTH, HEIGHT], land);
const pathGen = d3geo.geoPath(projection);
const landPath = pathGen(land);

const REGIONS = [
  { name: "Frankfurt", lon: 8.6821, lat: 50.1109 },
  { name: "New York", lon: -74.006, lat: 40.7128 },
  { name: "São Paulo", lon: -46.6333, lat: -23.5505 },
  { name: "Singapore", lon: 103.8198, lat: 1.3521 },
  { name: "Sydney", lon: 151.2093, lat: -33.8688 },
];

const regions = REGIONS.map((r) => {
  const [x, y] = projection([r.lon, r.lat]);
  return { name: r.name, x: Math.round(x * 100) / 100, y: Math.round(y * 100) / 100 };
});

const out = `// AUTO-GENERATED by scripts/generate-world-map.cjs — do not edit by hand.
// Real Natural-Earth-projected world landmass path (world-atlas countries-110m,
// merged to a single silhouette) plus projected coordinates for Trayon's
// validator anchor regions. viewBox is 0 0 ${WIDTH} ${HEIGHT}.

export const WORLD_MAP_WIDTH = ${WIDTH};
export const WORLD_MAP_HEIGHT = ${HEIGHT};

export const WORLD_LAND_PATH =
  "${landPath}";

export interface ValidatorRegion {
  name: string;
  x: number;
  y: number;
}

export const VALIDATOR_REGIONS: ValidatorRegion[] = ${JSON.stringify(regions, null, 2)};
`;

const outPath = path.join(__dirname, "..", "src", "components", "worldMapData.ts");
fs.writeFileSync(outPath, out);
console.log("Wrote", outPath, `(${landPath.length} chars path data)`);
